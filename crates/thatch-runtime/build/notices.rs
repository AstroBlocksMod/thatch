//! The license notices of the runtime: which libraries end up in an executable Thatch builds, under
//! which license each is taken, and the texts those licenses want shipped with the executable.
//!
//! The build script (`build.rs`) uses this to write the notices next to `libthatch_runtime.a`, and
//! `tests/notices.rs` uses it to check [`LINKED_CRATES`] against the dependency tree, so a new
//! dependency of the runtime cannot arrive without someone looking at its license.

use std::collections::{BTreeSet, HashMap};
use std::ffi::OsStr;
use std::fmt::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

/// A crate from crates.io that is linked into executables.
#[derive(Debug, Clone, Copy)]
pub struct LinkedCrate {
    pub name: &'static str,
    /// The license Thatch takes the crate under, one of those the crate offers.
    pub license: &'static str,
    /// The files in the crate's source that hold the text that license wants shipped. Empty when
    /// the license asks for nothing in a compiled program.
    pub files: &'static [&'static str],
}

const fn mit(name: &'static str, file: &'static [&'static str]) -> LinkedCrate {
    LinkedCrate { name, license: "MIT", files: file }
}

/// Every crate from crates.io the runtime links on some platform, sorted by name. The crates of
/// this repository are Thatch's own and are not listed.
///
/// Before adding one, check that its license is in [`ALLOWED_LICENSES`] (nothing copyleft may be
/// linked into what Thatch builds) and update the list in `docs/getting-started.md`.
pub const LINKED_CRATES: &[LinkedCrate] = &[
    mit("cfg-if", &["LICENSE-MIT"]),
    mit("corosensei", &["LICENSE-MIT"]),
    mit("libc", &["LICENSE-MIT"]),
    // The Boost license asks for no notice in "machine-executable object code generated by a
    // source language processor", which is all of ryu-js an executable holds.
    LinkedCrate { name: "ryu-js", license: "BSL-1.0", files: &[] },
    mit("scopeguard", &["LICENSE-MIT"]),
    // Windows only: the bindings corosensei uses, and the import libraries behind them.
    mit("windows-sys", &["license-mit"]),
    mit("windows-targets", &["license-mit"]),
    mit("windows_aarch64_gnullvm", &["license-mit"]),
    mit("windows_aarch64_msvc", &["license-mit"]),
    mit("windows_i686_gnu", &["license-mit"]),
    mit("windows_i686_gnullvm", &["license-mit"]),
    mit("windows_i686_msvc", &["license-mit"]),
    mit("windows_x86_64_gnu", &["license-mit"]),
    mit("windows_x86_64_gnullvm", &["license-mit"]),
    mit("windows_x86_64_msvc", &["license-mit"]),
];

/// The licenses a linked crate may be taken under: permissive ones only. A notice is fine, since
/// Rust's standard library already brings that duty into every executable; copyleft is not.
pub const ALLOWED_LICENSES: &[&str] =
    &["0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "BSL-1.0", "ISC", "MIT", "Unicode-3.0", "Zlib"];

/// A package as `cargo metadata` describes it.
#[derive(Debug, Clone)]
pub struct Package {
    pub name: String,
    pub version: String,
    /// The SPDX expression of the licenses the crate offers.
    pub license: String,
    /// The directory of the crate's source.
    pub dir: PathBuf,
}

/// What `cargo metadata` says the package at `manifest` links.
pub struct Linked {
    /// The packages from a registry among its normal dependencies, direct and indirect, sorted by
    /// name and version. Packages that come from a path are this repository's own and left out.
    pub packages: Vec<Package>,
    /// The lock file the answer came from, when the workspace has one.
    pub lock_file: PathBuf,
}

/// Asks `cargo metadata` which packages the package at `manifest` links: its normal dependencies,
/// direct and indirect, without build and dev dependencies. With a `target` triple only those
/// linked on that platform count; without one, those of every platform.
pub fn linked_packages(cargo: &OsStr, manifest: &Path, target: Option<&str>, offline: bool) -> Result<Linked, String> {
    let mut command = Command::new(cargo);
    command.args(["metadata", "--format-version", "1", "--manifest-path"]).arg(manifest);
    if let Some(target) = target {
        command.args(["--filter-platform", target]);
    }
    if offline {
        command.arg("--offline");
    }
    let output = command.output().map_err(|e| format!("could not run cargo metadata: {e}"))?;
    if !output.status.success() {
        return Err(format!("cargo metadata failed: {}", String::from_utf8_lossy(&output.stderr).trim()));
    }
    let metadata: serde_json::Value =
        serde_json::from_slice(&output.stdout).map_err(|e| format!("cargo metadata printed no JSON: {e}"))?;
    let missing = |what: &str| format!("cargo metadata printed no {what}");

    let packages = metadata["packages"].as_array().ok_or_else(|| missing("packages"))?;
    let manifest = manifest.canonicalize().unwrap_or_else(|_| manifest.to_owned());
    let same_file = |p: &serde_json::Value| {
        p["manifest_path"].as_str().is_some_and(|m| Path::new(m).canonicalize().is_ok_and(|m| m == manifest))
    };
    let root = packages.iter().find(|p| same_file(p)).ok_or_else(|| missing("package for the manifest"))?;
    let root = root["id"].as_str().ok_or_else(|| missing("package id"))?;

    // The resolved graph: what each package depends on, and in which role.
    let nodes = metadata["resolve"]["nodes"].as_array().ok_or_else(|| missing("dependency graph"))?;
    let mut normal_deps: HashMap<&str, Vec<&str>> = HashMap::new();
    for node in nodes {
        let id = node["id"].as_str().ok_or_else(|| missing("node id"))?;
        let deps = node["deps"].as_array().ok_or_else(|| missing("node dependencies"))?;
        let normal = deps
            .iter()
            .filter(|d| d["dep_kinds"].as_array().is_some_and(|kinds| kinds.iter().any(|k| k["kind"].is_null())))
            .filter_map(|d| d["pkg"].as_str());
        normal_deps.insert(id, normal.collect());
    }
    let mut linked = BTreeSet::new();
    let mut todo = vec![root];
    while let Some(id) = todo.pop() {
        for dep in normal_deps.get(id).map(Vec::as_slice).unwrap_or_default() {
            if linked.insert(*dep) {
                todo.push(dep);
            }
        }
    }

    let mut found = Vec::new();
    for package in packages {
        let id = package["id"].as_str().ok_or_else(|| missing("package id"))?;
        if !linked.contains(id) || package["source"].is_null() {
            continue;
        }
        let text = |key: &str| package[key].as_str().unwrap_or_default().to_owned();
        let dir = Path::new(&text("manifest_path")).parent().map(Path::to_owned).unwrap_or_default();
        found.push(Package { name: text("name"), version: text("version"), license: text("license"), dir });
    }
    found.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    let lock_file = Path::new(metadata["workspace_root"].as_str().unwrap_or_default()).join("Cargo.lock");
    Ok(Linked { packages: found, lock_file })
}

/// Whether the SPDX expression `offered` lets a crate be taken under `license` alone: the license
/// is one side of an `OR`, or the whole expression. Good enough for the expressions crates use;
/// anything it cannot read counts as no.
pub fn offers(offered: &str, license: &str) -> bool {
    // The old spelling of `OR`.
    let offered = offered.replace('/', " OR ");
    !offered.contains(" AND ")
        && !offered.contains(" WITH ")
        && offered.split(" OR ").any(|l| l.trim().trim_matches(['(', ')']).trim() == license)
}

/// The files in a crate's source that look like license texts, for a crate [`LINKED_CRATES`] does
/// not know: better too many notices than too few.
fn license_files(dir: &Path) -> Vec<String> {
    const PREFIXES: [&str; 6] = ["license", "licence", "copying", "notice", "copyright", "unlicense"];
    let mut files: Vec<String> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter(|e| e.path().is_file())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|name| PREFIXES.iter().any(|p| name.to_lowercase().starts_with(p)))
        .collect();
    files.sort();
    files
}

const RULE: &str = "--------------------------------------------------------------------------------";

/// The notices a program built with this runtime has to ship.
pub struct Notices {
    /// The notices as one text file.
    pub text: String,
    /// What could not be gathered and is therefore missing from the text.
    pub missing: Vec<String>,
    /// Crates that are linked but not in [`LINKED_CRATES`]. Their notices are in the text, but
    /// nobody has looked at their licenses.
    pub unlisted: Vec<String>,
}

/// Puts the notices together. `packages` are the crates linked on `target`. `rust_notices` is the
/// standard library's part, from [`rust_notices`], or the reason it is missing.
pub fn notices(target: &str, packages: &[Package], rust_notices: Result<String, String>) -> Notices {
    let mut warnings = Vec::new();
    let mut unlisted = Vec::new();
    let mut contents = String::new();
    let mut sections = String::new();
    for package in packages {
        let known = LINKED_CRATES.iter().find(|c| c.name == package.name);
        let (license, files) = match known {
            Some(c) => (c.license.to_owned(), c.files.iter().map(|f| (*f).to_owned()).collect::<Vec<_>>()),
            None => {
                unlisted.push(format!(
                    "{} {} is linked into executables but is not in LINKED_CRATES in build/notices.rs; \
                     every license file it has was copied into the notices",
                    package.name, package.version
                ));
                (package.license.clone(), license_files(&package.dir))
            }
        };
        let title = format!("{} {}", package.name, package.version);
        if known.is_some_and(|c| c.files.is_empty()) {
            let _ = writeln!(contents, "  {title} ({license}, which asks for no notice in a compiled program)");
            continue;
        }
        let _ = writeln!(contents, "  {title} ({license})");
        let _ = write!(sections, "\n{RULE}\n{title}\n");
        let _ = writeln!(sections, "License: {license}");
        let _ = writeln!(sections, "https://crates.io/crates/{}/{}", package.name, package.version);
        if files.is_empty() {
            warnings.push(format!("{title} has no license file to copy into the notices"));
        }
        for file in files {
            match std::fs::read_to_string(package.dir.join(&file)) {
                Ok(text) => {
                    let _ = write!(sections, "\n{file}:\n\n{}\n", text.trim_end());
                }
                Err(e) => warnings.push(format!("the license file {file} of {title} could not be read: {e}")),
            }
        }
    }
    let _ = writeln!(contents, "  The Rust standard library and the libraries built into it (MIT or Apache-2.0)");
    let _ = write!(sections, "\n{RULE}\nThe Rust standard library\n\n");
    match rust_notices {
        Ok(text) => sections.push_str(&text),
        Err(reason) => {
            warnings.push(format!("the notices of the Rust standard library are missing: {reason}"));
            sections.push_str(RUST_NOTICES_MISSING);
        }
    }

    let mut out = String::new();
    let _ = write!(
        out,
        "\
License notices
===============

This program was built with Thatch (https://github.com/AstroBlocksMod/thatch). The Thatch runtime
that is part of it is licensed under Apache-2.0 WITH LLVM-exception, which asks for no notice in a
compiled program. The runtime is built from the libraries listed below, and their licenses ask
that the notices in this file go along with every copy of the program.

Gathered for {target}.

Contents
--------

{contents}{sections}"
    );
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Notices { text: out, missing: warnings, unlisted }
}

/// What the notices say when the toolchain did not come with the standard library's copyright
/// file, as one installed without rustup may not.
const RUST_NOTICES_MISSING: &str = "\
The Rust standard library is licensed under the MIT license or the Apache License 2.0, at your
option. The toolchain this runtime was built with did not include the file that lists its
copyright notices and those of the libraries built into it, so they are not reproduced here. A
toolchain installed by rustup has that file as share/doc/rust/COPYRIGHT-library.html; ship it
with this program, or build the runtime with such a toolchain.
";

/// The copyright notices of the standard library and of the libraries built into it, as plain
/// text, from the `COPYRIGHT-library.html` a toolchain ships in `sysroot`.
///
/// That file also covers crates that only build or test the standard library. Only the crates
/// found as libraries in the sysroot of `target` are kept, since those are the ones that can be
/// linked. When the sysroot has none to compare with, everything is kept.
pub fn rust_notices(sysroot: &Path, target: &str) -> Result<String, String> {
    let path = sysroot.join("share/doc/rust/COPYRIGHT-library.html");
    let html = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let crates = sysroot_crates(&sysroot.join("lib/rustlib").join(target).join("lib"));
    Ok(html_to_text(&keep_linked_crates(&html, &crates)))
}

/// The names of the crates whose libraries are in a sysroot's library directory, as the files spell
/// them (`cfg_if` for `libcfg_if-0123abcd.rlib`).
fn sysroot_crates(lib_dir: &Path) -> BTreeSet<String> {
    std::fs::read_dir(lib_dir)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let name = name.strip_prefix("lib")?.strip_suffix(".rlib")?;
            Some(name.rsplit_once('-').map_or(name, |(name, _hash)| name).to_owned())
        })
        .collect()
}

/// Drops the sections of crates that are not in `crates` from the copyright file. Each crate has a
/// section that starts with a third-level heading such as `cfg-if-1.0.4`; what comes before the
/// first one covers the standard library itself and always stays. With no crates to compare with,
/// or no such headings, the file is returned whole.
fn keep_linked_crates(html: &str, crates: &BTreeSet<String>) -> String {
    const HEADING: &str = "<h3>";
    let Some(first) = html.find(HEADING) else { return html.to_owned() };
    if crates.is_empty() {
        return html.to_owned();
    }
    let mut kept = html[..first].to_owned();
    let mut rest = &html[first..];
    while !rest.is_empty() {
        let end = rest[HEADING.len()..].find(HEADING).map_or(rest.len(), |i| i + HEADING.len());
        let section = &rest[..end];
        let heading = section[HEADING.len()..].split("</h3>").next().unwrap_or_default();
        let heading = heading_text(heading).replace('-', "_");
        // `cfg_if_1.0.4` belongs to the crate `cfg_if`: the name, then the version.
        let linked = crates.iter().any(|name| {
            heading.strip_prefix(name.as_str()).and_then(|v| v.strip_prefix('_')).is_some_and(starts_with_digit)
        });
        if linked {
            kept.push_str(section);
        }
        rest = &rest[end..];
    }
    kept
}

fn starts_with_digit(s: &str) -> bool {
    s.starts_with(|c: char| c.is_ascii_digit())
}

/// A heading without the symbol Rust's copyright file puts in front of crate names.
fn heading_text(html: &str) -> String {
    let text = decode_entities(html);
    text.trim().trim_start_matches(|c: char| !c.is_ascii() || c.is_whitespace()).to_owned()
}

/// Turns simple HTML into plain text: tags go, block elements start new lines, entities become
/// characters, and `<pre>` blocks, which hold the license texts, keep their layout. A `<pre>` block
/// with the same text as an earlier one is replaced by a line that says where to find it, since the
/// same license text otherwise repeats for every crate.
pub fn html_to_text(html: &str) -> String {
    let mut out = String::new();
    // Where each license text first appeared, by its text without the whitespace.
    let mut seen: HashMap<String, String> = HashMap::new();
    let mut heading = String::new();
    let mut summary = String::new();
    let mut rest = html;
    while let Some(lt) = rest.find('<') {
        push_text(&mut out, &rest[..lt]);
        let Some(gt) = rest[lt..].find('>') else {
            rest = "";
            break;
        };
        let tag = &rest[lt + 1..lt + gt];
        rest = &rest[lt + gt + 1..];
        let closing = tag.starts_with('/');
        let name: String = tag
            .trim_start_matches('/')
            .chars()
            .take_while(char::is_ascii_alphanumeric)
            .collect::<String>()
            .to_lowercase();
        // The text up to the closing tag of the element that just opened, and what follows it.
        let element = |rest: &'_ str| -> (String, usize) {
            let close = format!("</{name}>");
            let end = rest.find(&close).unwrap_or(rest.len());
            (rest[..end].to_owned(), (end + close.len()).min(rest.len()))
        };
        match name.as_str() {
            "head" | "style" | "script" if !closing => {
                let (_, after) = element(rest);
                rest = &rest[after..];
            }
            "pre" if !closing => {
                let (text, after) = element(rest);
                rest = &rest[after..];
                let text = decode_entities(&text);
                let text = text.trim_matches(['\n', '\r']).trim_end();
                let key: String = text.split_whitespace().collect();
                let here = if summary.is_empty() { heading.clone() } else { format!("{summary} of {heading}") };
                paragraph(&mut out);
                match seen.get(&key) {
                    Some(first) => {
                        let _ = writeln!(out, "(The same text as {first}, above.)");
                    }
                    None => {
                        seen.insert(key, here);
                        out.push_str(text);
                        out.push('\n');
                    }
                }
                paragraph(&mut out);
            }
            "h1" | "h2" | "h3" | "h4" | "h5" | "h6" if !closing => {
                let (text, after) = element(rest);
                rest = &rest[after..];
                heading = heading_text(&strip_tags(&text));
                summary.clear();
                paragraph(&mut out);
                let _ = writeln!(out, "{heading}\n{}", "-".repeat(heading.chars().count()));
                paragraph(&mut out);
            }
            "summary" if !closing => {
                let (text, after) = element(rest);
                rest = &rest[after..];
                summary = heading_text(&strip_tags(&text));
                paragraph(&mut out);
                let _ = writeln!(out, "{summary}:");
            }
            "p" | "div" | "details" | "ul" | "ol" | "table" => paragraph(&mut out),
            "li" | "br" | "tr" => line(&mut out),
            _ => {}
        }
    }
    push_text(&mut out, rest);
    let mut text = out.trim().to_owned();
    text.push('\n');
    text
}

/// The text of a fragment of HTML without its tags.
fn strip_tags(html: &str) -> String {
    let mut out = String::new();
    let mut rest = html;
    while let Some(lt) = rest.find('<') {
        out.push_str(&rest[..lt]);
        rest = rest[lt..].find('>').map_or("", |gt| &rest[lt + gt + 1..]);
    }
    out.push_str(rest);
    out
}

/// Appends running text: entities decoded, every run of whitespace one space.
fn push_text(out: &mut String, html: &str) {
    let text = decode_entities(html);
    let at_line_start = out.is_empty() || out.ends_with('\n');
    if text.starts_with(char::is_whitespace) && !at_line_start && !out.ends_with(' ') {
        out.push(' ');
    }
    let mut words = 0;
    for word in text.split_whitespace() {
        if words > 0 {
            out.push(' ');
        }
        out.push_str(word);
        words += 1;
    }
    // A space before whatever comes next on the line; the end of a line drops it again.
    if words > 0 && text.ends_with(char::is_whitespace) {
        out.push(' ');
    }
}

/// Ends the current line, if there is one.
fn line(out: &mut String) {
    let trimmed = out.trim_end_matches(' ').len();
    out.truncate(trimmed);
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
}

/// Ends the current paragraph: one blank line, however many block elements end here.
fn paragraph(out: &mut String) {
    line(out);
    if !out.is_empty() && !out.ends_with("\n\n") {
        out.push('\n');
    }
}

/// Replaces the character references HTML uses: `&#60;`, `&#x3c;` and the few named ones that
/// appear in generated files. Anything else is left as it is.
fn decode_entities(html: &str) -> String {
    let mut out = String::with_capacity(html.len());
    let mut rest = html;
    while let Some(amp) = rest.find('&') {
        out.push_str(&rest[..amp]);
        rest = &rest[amp..];
        let end = rest.find(';').filter(|end| *end <= 10);
        let decoded = end.and_then(|end| {
            let name = &rest[1..end];
            let code = match name.strip_prefix('#') {
                Some(number) => match number.strip_prefix(['x', 'X']) {
                    Some(hex) => u32::from_str_radix(hex, 16).ok(),
                    None => number.parse().ok(),
                },
                None => match name {
                    "amp" => Some(u32::from('&')),
                    "lt" => Some(u32::from('<')),
                    "gt" => Some(u32::from('>')),
                    "quot" => Some(u32::from('"')),
                    "apos" => Some(u32::from('\'')),
                    "nbsp" => Some(u32::from(' ')),
                    _ => None,
                },
            };
            code.and_then(char::from_u32).map(|c| (c, end))
        });
        match decoded {
            Some((c, end)) => {
                out.push(c);
                rest = &rest[end + 1..];
            }
            None => {
                out.push('&');
                rest = &rest[1..];
            }
        }
    }
    out.push_str(rest);
    out
}
